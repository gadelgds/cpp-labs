/**
 * @file task5_char_reading.cpp
 * @brief Задача 5 (Фото 2, Задача 3): Посимвольное чтение строки и подсчет пробелов.
 * 
 * УСЛОВИЕ:
 * Напишите программу, которая считывает текст из консоли по одному символу
 * с помощью функции getchar() до тех пор, пока не встретит символ переноса
 * строки ('\n'). Программа должна подсчитать и вывести, сколько пробелов было введено.
 * 
 * ПОШАГОВОЕ ОБЪЯСНЕНИЕ РЕШЕНИЯ:
 * 1. Использование функции getchar():
 *    - getchar() объявлена в заголовке <cstdio> (или <stdio.h>).
 *    - Она считывает ровно один очередной символ из стандартного потока ввода (stdin).
 *    - Возвращаемый тип — 'int', а не 'char'! Это необходимо для того, чтобы корректно
 *      обрабатывать специальное отрицательное значение EOF (-1), сигнализирующее
 *      о конце файла или ошибке потока.
 * 
 * 2. Организация цикла:
 *    - В цикле считывается каждый символ: while ((ch = getchar()) != '\n' && ch != EOF)
 *    - Условие завершения: обнаружение символа '\n' (нажатие Enter) или EOF.
 * 
 * 3. Подсчет пробелов:
 *    - Инициализируем счетчик: int spaceCount = 0;
 *    - Внутри тела цикла проверяем условие: if (ch == ' ') { spaceCount++; }
 * 
 * 4. Завершение и вывод:
 *    - После выхода из цикла выводим итоговое значение счетчика.
 */

#include <iostream>
#include <cstdio>

int main() {
    #if defined(_WIN32)
    system("chcp 65001 > nul");
    #endif

    std::cout << "=== ЗАДАЧА 5: Посимвольное чтение строки через getchar() ===" << std::endl;
    std::cout << "Введите строку текста и нажмите [Enter]:" << std::endl;
    std::cout << "> ";

    int ch;             // Переменная типа int для символа (чтобы вместить EOF)
    int spaceCount = 0; // Счетчик пробелов
    int totalCount = 0; // Общее число введенных символов

    // Шаг 1: Цикл посимвольного чтения
    while ((ch = getchar()) != '\n' && ch != EOF) {
        totalCount++;

        // Шаг 2: Проверка, является ли символ пробелом
        if (ch == ' ') {
            spaceCount++;
        }
    }

    // Шаг 3: Вывод результатов
    std::cout << "\n--- РЕЗУЛЬТАТЫ ПОДСЧЕТА ---" << std::endl;
    std::cout << "Всего символов введено: " << totalCount << std::endl;
    std::cout << "Количество пробелов:     " << spaceCount << std::endl;

    return 0;
}
