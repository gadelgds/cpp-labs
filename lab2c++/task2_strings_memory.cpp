/**
 * @file task2_strings_memory.cpp
 * @brief Задача 2 (Фото 1): Строки и массивы в памяти.
 * 
 * УСЛОВИЕ:
 * Что выведет программа? Чему равен sizeof(str) и sizeof(p) в 64-битной системе?
 * 
 * #include <iostream>
 * int main() {
 *     char str[] = "Hello";
 *     const char* p = "Hello";
 *     std::cout << sizeof(str) << " " << sizeof(p) << std::endl;
 *     return 0;
 * }
 * 
 * ОТВЕТ:
 * В 64-битной системе программа выведет:
 * 6 8
 * 
 * (В 32-битной системе вывод был бы: 6 4)
 * 
 * ПОШАГОВОЕ ОБЪЯСНЕНИЕ:
 * 1. char str[] = "Hello";
 *    - Это объявление локального символьного массива фиксированного размера на стеке.
 *    - Строковый литерал "Hello" состоит из 5 букв ('H', 'e', 'l', 'l', 'o') 
 *      и невидимого завершающего нуль-терминатора '\0' (байт со значением 0).
 *    - Компилятор вычисляет размер массива автоматически: 5 + 1 = 6 элементов типа char.
 *    - Каждый char занимает ровно 1 байт.
 *    - Оператор sizeof(str) возвращает полный размер массива в памяти, т.е. 6 байт.
 * 
 * 2. const char* p = "Hello";
 *    - Здесь 'p' — это НЕ массив, а переменная-указатель.
 *    - Строковый литерал "Hello" размещается компилятором в неизменяемой секции данных бинарника (read-only data, .rdata).
 *    - Переменная 'p' хранит лишь адрес первого байта этой строки в памяти.
 *    - Оператор sizeof(p) вычисляет размер САМОГО УКАЗАТЕЛЯ, а НЕ строки, на которую он указывает!
 *    - В 64-битной архитектуре (x64 / AMD64) любой указатель занимает 8 байт (64 бита адреса).
 *    - (Для справки: длина самой строки вычисляется функцией strlen(p) и равна 5).
 * 
 * 3. std::cout << sizeof(str) << " " << sizeof(p) << std::endl;
 *    - Выводится: 6 8 (в x64 системе).
 */

#include <iostream>
#include <cstring>

int main() {
    #if defined(_WIN32)
    system("chcp 65001 > nul");
    #endif

    std::cout << "=== ЗАДАЧА 2: Строки и массивы в памяти ===" << std::endl;

    char str[] = "Hello";
    const char* p = "Hello";

    std::cout << "\n--- РЕЗУЛЬТАТ ВЫВОДА ПО УСЛОВИЮ ---" << std::endl;
    std::cout << sizeof(str) << " " << sizeof(p) << std::endl;

    std::cout << "\n--- ПОДРОБНЫЙ АНАЛИЗ ПАМЯТИ ---" << std::endl;
    std::cout << "Разрядность текущей сборки: " << (sizeof(void*) * 8) << "-бит" << std::endl;
    std::cout << "sizeof(str) = " << sizeof(str) 
              << " байт (массив из 5 букв + 1 нуль-терминатор '\\0')" << std::endl;
    std::cout << "sizeof(p)   = " << sizeof(p) 
              << " байт (размер указателя в " << (sizeof(void*) * 8) << "-битной архитектуре)" << std::endl;
    std::cout << "strlen(str) = " << strlen(str) << " (число символов без '\\0')" << std::endl;
    std::cout << "strlen(p)   = " << strlen(p)   << " (число символов без '\\0')" << std::endl;

    std::cout << "\nБайтовое представление массива str[]:" << std::endl;
    for (size_t i = 0; i < sizeof(str); ++i) {
        std::cout << "  str[" << i << "] = '" << (str[i] == '\0' ? "\\0" : std::string(1, str[i])) 
                  << "' (код ASCII: " << (int)(unsigned char)str[i] << ")" << std::endl;
    }

    return 0;
}
