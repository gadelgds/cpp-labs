/**
 * @file task1_pointers.cpp
 * @brief Задача 1 (Фото 1): Базовые операции с указателями.
 * 
 * УСЛОВИЕ:
 * Что выведет данный фрагмент кода?
 * 
 * int a = 10;
 * int b = 20;
 * int* p = &a;
 * *p = 30;
 * p = &b;
 * *p = 40;
 * std::cout << a << " " << b << std::endl;
 * 
 * ВЫВОД ПРОГРАММЫ:
 * 30 40
 * 
 * ПОШАГОВОЕ ОБЪЯСНЕНИЕ:
 * 1. int a = 10; int b = 20;
 *    В стековой памяти выделяются две ячейки для целочисленных переменных:
 *    - переменная 'a' со значением 10;
 *    - переменная 'b' со значением 20.
 * 
 * 2. int* p = &a;
 *    Создается переменная-указатель 'p' типа int*.
 *    Оператор взятия адреса (&) возвращает адрес ячейки 'a'.
 *    Теперь указатель p хранит адрес переменной a (ссылается на a).
 * 
 * 3. *p = 30;
 *    Оператор разыменования (*) обращается к области памяти, на которую указывает p.
 *    Так как p указывает на a, в ячейку переменной a записывается значение 30.
 *    Состояние: a = 30, b = 20.
 * 
 * 4. p = &b;
 *    Указателю p присваивается адрес переменной b.
 *    Важно: значение по старому адресу (a) не меняется, меняется сам указатель p.
 *    Теперь p ссылается на b.
 * 
 * 5. *p = 40;
 *    Разыменовываем p и записываем 40 в память по адресу в p.
 *    Так как p теперь указывает на b, изменяется значение переменной b.
 *    Состояние: a = 30, b = 40.
 * 
 * 6. std::cout << a << " " << b << std::endl;
 *    Выводятся текущие значения a и b через пробел: "30 40".
 */

#include <iostream>

int main() {
    // Включение поддержки UTF-8 для корректного вывода в терминале
    #if defined(_WIN32)
    system("chcp 65001 > nul");
    #endif

    std::cout << "=== ЗАДАЧА 1: Базовые операции с указателями ===" << std::endl;

    // Шаг 1: Инициализация переменных
    int a = 10;
    int b = 20;
    std::cout << "[Шаг 1] Исходные значения: a = " << a << ", b = " << b << std::endl;
    std::cout << "        Адрес a: " << &a << ", Адрес b: " << &b << std::endl;

    // Шаг 2: Указатель p указывает на a
    int* p = &a;
    std::cout << "[Шаг 2] int* p = &a; -> p указывает на a (адрес: " << p << ")" << std::endl;

    // Шаг 3: Разыменование и перезапись значения a
    *p = 30;
    std::cout << "[Шаг 3] *p = 30;     -> значение a изменено через указатель: a = " << a << std::endl;

    // Шаг 4: Перенаправление указателя на b
    p = &b;
    std::cout << "[Шаг 4] p = &b;      -> теперь p указывает на b (адрес: " << p << ")" << std::endl;

    // Шаг 5: Разыменование и перезапись значения b
    *p = 40;
    std::cout << "[Шаг 5] *p = 40;     -> значение b изменено через указатель: b = " << b << std::endl;

    // Шаг 6: Финальный вывод (как в условии задачи)
    std::cout << "\n--- РЕЗУЛЬТАТ ВЫВОДА ПО УСЛОВИЮ ---" << std::endl;
    std::cout << a << " " << b << std::endl;

    return 0;
}
