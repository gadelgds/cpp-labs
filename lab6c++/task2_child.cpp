#include <windows.h>
#include <iostream>

int main() {
    #if defined(_WIN32)
    system("chcp 65001 > nul");
    #endif

    std::cout << "=== ЗАДАНИЕ 2: CHILD (ПОТОМОК) ===" << std::endl;

    // 1. Читаем переменную STUDENT_ID из СОБСТВЕННОГО блока окружения
    //    этого процесса. Блок окружения потомок получил от родителя
    //    в момент CreateProcess — это КОПИЯ (снимок) блока родителя,
    //    а не общая память. Поэтому то, что родитель делает со своей
    //    переменной ПОСЛЕ запуска, на нас уже никак не влияет.
    const wchar_t* varName = L"STUDENT_ID";
    wchar_t buffer[256];

    //    GetEnvironmentVariable возвращает длину значения (без завершающего
    //    нуля). 0 означает: переменная не найдена (или её значение — пустая
    //    строка; различают по GetLastError() == ERROR_ENVVAR_NOT_FOUND).
    DWORD len = GetEnvironmentVariable(varName, buffer, sizeof(buffer) / sizeof(buffer[0]));

    if (len == 0) {
        DWORD err = GetLastError();
        if (err == ERROR_ENVVAR_NOT_FOUND) {
            std::cout << "ОШИБКА: переменная STUDENT_ID не найдена в блоке окружения." << std::endl;
            std::cout << "Скорее всего, Child.exe запущен напрямую, без Parent.exe," << std::endl;
            std::cout << "поэтому никто не установил эту переменную перед запуском." << std::endl;
        } else {
            std::cout << "Ошибка GetEnvironmentVariable: " << err << std::endl;
        }
    } else {
        // 2. Переменная найдена — выводим её значение.
        std::cout << "Child: прочитана переменная STUDENT_ID=";
        std::wcout << buffer << std::endl;

        // 3. Доказательство автономности: сравниваем со значением,
        //    которое установил родитель ДО запуска (19045).
        //    Родитель после запуска перезаписал её у себя на 99999,
        //    но наша копия не изменилась — процессы изолированы.
        if (wcscmp(buffer, L"19045") == 0) {
            std::cout << "Child: значение равно 19045 — оно НЕ изменилось вслед за родителем." << std::endl;
            std::cout << "Child: доказано — Environment Block копируется при создании процесса," << std::endl;
            std::cout << "Child: потомок живёт со своим снимком окружения, а не с общей памятью." << std::endl;
        } else {
            std::cout << "Child: ВНИМАНИЕ: значение отличается от ожидаемого 19045!" << std::endl;
            std::cout << "Child: возможно, Child.exe запущен не из-под Parent.exe," << std::endl;
            std::cout << "Child: а из среды, где STUDENT_ID уже была задана иначе." << std::endl;
        }
    }

    // 4. Ждём нажатия клавиши, чтобы окно консоли не закрылось раньше,
    //    чем пользователь увидит вывод. Без этой паузы потомок завершился
    //    бы мгновенно — особенно если его запустили двойным кликом.
    //    system("pause") выводит "Для продолжения нажмите любую клавишу . . ."
    //    и ждёт нажатия. Родитель к этому моменту уже завершён —
    //    потомок продолжает работу самостоятельно.
    std::cout << "Child: родитель уже завершён, а потомок продолжает работу сам." << std::endl;
    system("pause");

    return 0;
}
